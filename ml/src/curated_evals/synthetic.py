"""A generated eval set for CI, and for smoke-testing the harness itself.

This exists so the metric code, the loader, the report and the config matrix all
have something to run against without a key and without the owner's screenshots.
It is **not** a substitute for the real benchmark, and every artifact it produces
carries `split: "synthetic"` plus a `SYNTHETIC` marker file, so a report built
from it cannot be mistaken for one built from real screenshots.

The images are drawn, not sampled from anywhere: a header bar, a couple of text
rows and a label word chosen from the taxonomy. The label is known because this
module chose it, which is the whole point - it makes the metrics testable, not
the model good.
"""

from __future__ import annotations

import csv
from pathlib import Path

from curated_evals.dataset import LABELS_FILENAME, SYNTHETIC_SPLIT, LabeledSet, load_set


MARKER_FILENAME = "SYNTHETIC"
NOTE_FILENAME = "README.md"

_TEMPLATES: tuple[tuple[str, str, str], ...] = (
    (
        "{label} reference card",
        "A saved reference card about {label_lower}.",
        "{label_lower}, reference, saved",
    ),
    (
        "{label} cheat sheet",
        "Step-by-step notes captured while working on {label_lower}.",
        "{label_lower}, notes, steps",
    ),
    (
        "{label} article",
        "An article read about {label_lower}, kept for later.",
        "{label_lower}, article, reading",
    ),
    (
        "{label} dashboard screenshot",
        "A dashboard screen showing {label_lower} metrics.",
        "{label_lower}, dashboard, metrics",
    ),
    (
        "{label} tutorial in progress",
        "Part way through a {label_lower} walkthrough.",
        "{label_lower}, tutorial, walkthrough",
    ),
    (
        "{label} inspiration board",
        "A mood board of {label_lower} examples.",
        "{label_lower}, inspiration, board",
    ),
)


def build_synthetic_set(
    root: str | Path,
    taxonomy_path: str | Path,
    *,
    per_label: int = 1,
) -> LabeledSet:
    """Render a synthetic set and return it as a loaded `LabeledSet`.

    `per_label` controls the size. One image per taxonomy label is the smallest
    set that exercises every per-class branch in the metrics.
    """
    from curated_ml.taxonomy import load_taxonomy

    taxonomy = load_taxonomy(taxonomy_path)
    directory = Path(root)
    directory.mkdir(parents=True, exist_ok=True)

    rows: list[dict[str, str]] = []
    index = 0
    for label in taxonomy.labels:
        for copy in range(per_label):
            template_title, template_desc, template_tags = _TEMPLATES[(index) % len(_TEMPLATES)]
            index += 1
            item_id = f"syn-{index:03d}"
            name = f"{item_id}.png"
            _render(directory / name, label, template_title.format(label=label))
            rows.append(
                {
                    "id": item_id,
                    "file": name,
                    "title": template_title.format(label=label),
                    "description": template_desc.format(label_lower=label.lower()),
                    "tags": template_tags.format(label_lower=label.lower()),
                    "category": label,
                }
            )

    labels_path = directory / LABELS_FILENAME
    with labels_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle, fieldnames=["id", "file", "title", "description", "tags", "category"]
        )
        writer.writeheader()
        writer.writerows(rows)

    (directory / MARKER_FILENAME).write_text(
        "Generated by curated_evals.synthetic. Not real screenshots.\n", encoding="utf-8"
    )
    (directory / NOTE_FILENAME).write_text(_README, encoding="utf-8")

    loaded = load_set(directory, taxonomy_path)
    assert loaded.split == SYNTHETIC_SPLIT
    return loaded


def _render(path: Path, label: str, title: str) -> None:
    """Draw a small, legible mock screen. Text is deliberately big."""
    from PIL import Image, ImageDraw

    width, height = 480, 320
    image = Image.new("RGB", (width, height), (245, 246, 248))
    draw = ImageDraw.Draw(image)
    draw.rectangle([0, 0, width, 44], fill=(38, 48, 66))
    draw.text((12, 16), title[:44], fill=(255, 255, 255))
    draw.text((12, 70), f"category: {label}", fill=(20, 20, 20))
    for row in range(6):
        y = 110 + row * 30
        draw.line([12, y, width - 12, y], fill=(210, 214, 220), width=2)
    image.save(path, format="PNG")


_README = """# Synthetic eval set

**These images are generated, not screenshots.** They exist so the harness, the
metric code and CI have something to run against without an API key.

Anything measured on this set says something about the code, never about model
quality. Every report built from this folder records `split: "synthetic"`.

Drop real screenshots in their own folder with a `labels.csv` and point
`python -m evals.run --set <folder>` at that instead.
"""
